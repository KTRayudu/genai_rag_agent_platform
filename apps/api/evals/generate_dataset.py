import os
import json
from dotenv import load_dotenv
from qdrant_client import QdrantClient
from langsmith import Client
from langchain_ollama import ChatOllama
from langchain_core.messages import SystemMessage, HumanMessage

# Load API keys (for LangSmith)
load_dotenv()

# ==========================================
# OPTIONS
# ==========================================
# This reads the 'FORCE' flag from your Makefile!
FORCE_REGENERATE = os.getenv("FORCE_REGENERATE", "false").lower() == "true"
# ==========================================

# 1. Connect to local Qdrant Vector DB
print("Connecting to Qdrant...")
qdrant_client = QdrantClient(url="http://localhost:6333")

# 2. Download raw chunks from the database
print("Downloading Amazon chunks from database...")
all_points = qdrant_client.scroll(
    collection_name="Amazon-items-collection-03",
    limit=50,
    offset=None,
    with_payload=True,
    with_vectors=False
)

# Parse the chunks
all_context = [{"id": data.payload["parent_asin"], "text": data.payload["description"]} for data in all_points[0]]

# 3. Setup the Prompts
SYSTEM_PROMPT = """
I am building a RAG application. I have a collection of 50 chunks of text.
The RAG application will act as a shopping assistant that can answer questions about the stock of the products we have available.
I will provide all of the available products to you with IDs of each chunk.
I want you to come up with 30 questions to which the answers could be grounded in the chunk context.
The questions should imitate a potential real user of this RAG system.
As an output I need you to provide me the list of questions and the IDs of the chunks that could be used to answer them.
Also, provide an example answer to the question given the context of the chunks.
Also, provide the reason why you chose the chunks to answer the questions.
Construct 10 questions that could use multipple chunks in the answer.
Construct 15 questions that could use single chunk in the answer.
Construct 5 questions that can't be answered with the available chunks.

<OUTPUT JSON SCHEMA>
{
  "type": "array",
  "items": {
    "type": "object",
    "properties": {
      "question": {
        "type": "string",
        "description": "Suggested question."
      },
      "chunk_ids": {
        "type": "array",
        "items": {
          "type": "string",
          "description": "CRITICAL: You MUST include the exact 'id' (parent_asin) of the chunks you used here. Do not leave this array empty."
        }
      },
      "answer_example": {
        "type": "string",
        "description": "Suggested answer grounded in the context."
      },
      "reasoning": {
        "type": "string",
        "description": "Reasoning why the question could be answered with the chunks."
      }
    }
  }
}
</OUTPUT JSON SCHEMA>

I need to be able to parse the json output.
"""

USER_PROMPT = f"""
Here is the list of chunks, each list element is a dictionary with id and text:
{all_context}
"""

# 4. Check if Dataset already exists in LangSmith to save time!
ls_client = Client()
DATASET_NAME = "ollama-70b-amazon-dataset"

try:
    if not FORCE_REGENERATE and ls_client.has_dataset(dataset_name=DATASET_NAME):
        print(f"✅ Dataset '{DATASET_NAME}' already exists in LangSmith!")
        print("Skipping LLM generation to save time.")
        print("-> If you want to force it to generate anyway, open this file and set FORCE_REGENERATE = True at the top!")
        exit(0)
except Exception:
    # If the method fails or it doesn't exist, proceed with generation
    pass

# 5. Use massive local model to generate the dataset
print("Generating new dataset using gpt-oss:120b. This may take a few minutes...")
llm = ChatOllama(model="gpt-oss:120b", format="json")

messages = [
    SystemMessage(content=SYSTEM_PROMPT),
    HumanMessage(content=USER_PROMPT)
]

response = llm.invoke(messages)

# 5. Parse the LLM's response
try:
    json_data = json.loads(response.content)
    # FIX: If the model returns {"type": "array", "items": [...]}, extract the array
    if isinstance(json_data, dict) and "items" in json_data:
        json_data = json_data["items"]
    elif isinstance(json_data, dict) and len(json_data) == 1:
        # Fallback if it wrapped it in another random key
        json_data = list(json_data.values())[0]
        
    print(f"Successfully generated {len(json_data)} new Q&A pairs!")
except Exception as e:
    print("Failed to parse JSON from the model!")
    print(response.content)
    exit(1)

# 7. Upload the new persistent dataset to LangSmith
print(f"Uploading new dataset '{DATASET_NAME}' to LangSmith...")
try:
    dataset = ls_client.create_dataset(
        dataset_name=DATASET_NAME,
        description="A completely synthetic dataset generated by local Ollama 70b"
    )
except Exception as e:
    print(f"Dataset might already exist: {e}")
    dataset = ls_client.read_dataset(dataset_name=DATASET_NAME)

for item in json_data:
    try:
        ls_client.create_example(
            inputs={"question": item["question"]},
            outputs={
                "answer": item["answer_example"],
                "reference_context_ids": item["chunk_ids"]
            },
            dataset_id=dataset.id
        )
    except Exception as e:
        print(f"Failed to upload example: {e}")

print("=========================================")
print("✅ Upload Complete!")
print(f"Your new persistent dataset '{DATASET_NAME}' is ready.")
print("Update eval_retriever.py to use this name, and run `make run-evals-retriever`.")
